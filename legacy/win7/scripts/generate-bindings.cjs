// Generates the frontend bindings the app imports and the Electron allowlist
// from the Go App method surface. Replaces `wails3 generate bindings`, which
// would drag the Wails CLI (and its WebView2 runtime assumptions) into the
// Win7 build.
const fs = require('node:fs')
const path = require('node:path')

const repoRoot = path.resolve(__dirname, '../../..')
const frontendRoot = path.join(repoRoot, 'frontend')
const bindingsRoot = path.join(frontendRoot, 'bindings', 'github.com', 'ys-ll', 'uniterm')
const methodsFile = path.join(repoRoot, 'legacy', 'win7', 'electron', 'app-methods.cjs')

const HEADER = '// Generated by legacy/win7/scripts/generate-bindings.cjs. DO NOT EDIT.\n'

function appMethods() {
  const names = new Set()
  for (const file of fs.readdirSync(repoRoot)) {
    if (!file.endsWith('.go') || file.endsWith('_test.go')) continue
    const source = fs.readFileSync(path.join(repoRoot, file), 'utf8')
    for (const match of source.matchAll(/^func \(a \*App\) ([A-Z][A-Za-z0-9_]*)\(/gm)) {
      names.add(match[1])
    }
  }
  return [...names].sort()
}

function writeAppBinding(methods) {
  const js = [HEADER.trimEnd(), 'import { Call as $Call } from "@wailsio/runtime";', '']
  const dts = [HEADER.trimEnd(), '// eslint-disable-next-line @typescript-eslint/no-explicit-any']
  for (const name of methods) {
    js.push(`export function ${name}(...args) {`)
    js.push(`  return $Call.ByName("main.App.${name}", ...args);`)
    js.push('}')
    js.push('')
    dts.push(`export declare function ${name}(...args: any[]): Promise<any>;`)
  }
  fs.mkdirSync(bindingsRoot, { recursive: true })
  fs.writeFileSync(path.join(bindingsRoot, 'app.js'), js.join('\n'))
  fs.writeFileSync(path.join(bindingsRoot, 'app.d.ts'), dts.join('\n') + '\n')
}

// Only the model types the frontend imports by name. Plain classes keep
// `new Model()` working; the RPC already returns plain JSON with the fields.
const MODELS = {
  'backend/database/models': ['ScriptResult'],
  'backend/sync/models': ['SyncConfig'],
}

function writeModels() {
  for (const [modulePath, classes] of Object.entries(MODELS)) {
    const parts = modulePath.split('/')
    const fileName = parts.pop()
    const outDir = path.join(bindingsRoot, ...parts)
    fs.mkdirSync(outDir, { recursive: true })
    const js = [HEADER.trimEnd(), ...classes.map(name => `export class ${name} {}`), '']
    const dts = [HEADER.trimEnd(), ...classes.map(name => `export declare class ${name} { [key: string]: any }`), '']
    fs.writeFileSync(path.join(outDir, `${fileName}.js`), js.join('\n'))
    fs.writeFileSync(path.join(outDir, `${fileName}.d.ts`), dts.join('\n'))
  }
}

function writeAllowlist(methods) {
  const body = HEADER + 'module.exports = [\n' + methods.map(name => `  ${JSON.stringify(name)},`).join('\n') + '\n]\n'
  fs.writeFileSync(methodsFile, body)
}

function generate() {
  const methods = appMethods()
  if (!methods.length) throw new Error('No App methods found in ' + repoRoot)
  writeAppBinding(methods)
  writeModels()
  writeAllowlist(methods)
  console.log(`Generated ${methods.length} App bindings.`)
  return methods
}

module.exports = { generate }

if (require.main === module) generate()